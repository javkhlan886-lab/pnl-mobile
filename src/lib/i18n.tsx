export const dictionaries = { mn, en, ko };
export type Dict = typeof mn;

export function format(template: string, vars: Record<string, string>): string {
  return Object.entries(vars).reduce((s, [k, v]) => s.replace(`{${k}}`, v), template);
}

async function getStoredLocale(): Promise<Locale | null> {
  const raw = Platform.OS === "web" ? window.localStorage.getItem(LOCALE_KEY) : await SecureStore.getItemAsync(LOCALE_KEY);
  return raw === "mn" || raw === "en" || raw === "ko" ? raw : null;
}

async function storeLocale(locale: Locale): Promise<void> {
  if (Platform.OS === "web") {
    window.localStorage.setItem(LOCALE_KEY, locale);
    return;
  }
  await SecureStore.setItemAsync(LOCALE_KEY, locale);
}

interface LocaleState {
  locale: Locale;
  t: Dict;
  setLocale: (l: Locale) => void;
}

const LocaleContext = createContext<LocaleState | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("mn");

  useEffect(() => {
    getStoredLocale().then((l) => {
      if (l) setLocaleState(l);
    });
  }, []);

  function setLocale(l: Locale) {
    setLocaleState(l);
    storeLocale(l);
  }

  return (
    <LocaleContext.Provider value={{ locale, t: dictionaries[locale], setLocale }}>
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale(): LocaleState {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error("useLocale must be used within LocaleProvider");
  return ctx;
}
